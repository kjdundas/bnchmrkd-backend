// Regenerates src/assets/wordmark.ts from the web app's canonical SVGs.
// Run from mobile/:  node scripts/gen-wordmark.js
// Source of truth is frontend/public/*.svg — never hand-edit wordmark.ts.
const fs = require('fs')
const path = require('path')

const PUBLIC = path.resolve(__dirname, '../../frontend/public')
const OUT = path.resolve(__dirname, '../src/assets/wordmark.ts')

function read(name) {
  const raw = fs.readFileSync(path.join(PUBLIC, name), 'utf8')
  // react-native-svg's SvgXml wants a bare <svg> root, no XML prolog.
  return raw.replace(/<\?xml[^>]*\?>\s*/i, '').trim()
}

const indigo = read('bnchmrkd-wordmark.svg')
const white = read('bnchmrkd-wordmark-white.svg')
const mark = read('favicon.svg')

const banner = `// AUTO-GENERATED by scripts/gen-wordmark.js — do not edit by hand.
// Source: frontend/public/{bnchmrkd-wordmark,bnchmrkd-wordmark-white,favicon}.svg
// Regenerate after any logo change:  node scripts/gen-wordmark.js
`

const body =
  banner +
  '\n/** Indigo wordmark — use on light surfaces. */\n' +
  'export const WORDMARK_INDIGO = ' + JSON.stringify(indigo) + '\n' +
  '\n/** White wordmark — use on dark surfaces (splash, auth). */\n' +
  'export const WORDMARK_WHITE = ' + JSON.stringify(white) + '\n' +
  "\n/** Square 'b' roundel — app-icon mark. */\n" +
  'export const BRAND_MARK = ' + JSON.stringify(mark) + '\n'

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, body)
console.log('wrote', path.relative(process.cwd(), OUT), '·', (body.length / 1024).toFixed(1) + 'KB')
